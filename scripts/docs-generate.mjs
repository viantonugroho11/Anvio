#!/usr/bin/env node
// Generates reference pages whose facts come straight from source code, so the
// docs cannot drift from the implementation:
//   docs/reference/builtin-tools.md  — tool catalog (packages/tools)
//   docs/reference/project-metrics.md — counts derived from the repository
//
// Usage: node scripts/docs-generate.mjs [--check]
//   --check  exit 1 when the committed pages are out of date (used in CI).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf-8');
const check = process.argv.includes('--check');

// ---------- tools ----------
function parseToolDescriptions() {
  const src = read('packages/tools/src/tool-descriptions.ts');
  const body = src.slice(src.indexOf('DEFAULT_DESCRIPTIONS'), src.indexOf('};'));
  const tools = [];
  // key: 'value' or key:\n    'value'  (values never contain an unescaped single quote)
  const re = /^\s{2}([a-z0-9_]+):\s*'((?:[^'\\]|\\.)*)'/gm;
  const flat = body.replace(/:\s*\n\s+'/g, ": '");
  for (const m of flat.matchAll(re))
    tools.push({ name: m[1], description: m[2].replace(/\\'/g, "'") });
  return tools;
}

function parseGatewayDefaults() {
  const src = read('packages/tools/src/gateway.ts');
  const start = src.indexOf('DEFAULT_TOOL_GATEWAY_YAML');
  const yaml = src.slice(start, src.indexOf('`;', start));
  const enabled = new Map();
  for (const m of yaml.matchAll(/^ {4}([a-z0-9_]+):\n {6}enabled: (true|false)/gm))
    enabled.set(m[1], m[2] === 'true');
  return enabled;
}

const CATEGORY_RULES = [
  [/^browser/, 'Browser automation'],
  [/^kanban_/, 'Kanban coordination'],
  [/^ha_/, 'Home Assistant'],
  [
    /^(delegate_task|a2a_delegate|mixture_of_agents|send_message|clarify|todo|session_search)$/,
    'Agents & orchestration',
  ],
  [/^(skill|skills_|mcp_manage|cronjob)/, 'Skills, MCP & scheduling'],
  [/^(web_|http_request|x_search)/, 'Web & network'],
  [
    /^(file_|append_file|edit_file|patch_file|list_dir|path_exists|glob_files|grep_search|search_files)/,
    'Workspace files',
  ],
  [/^(execute_code|run_shell|terminal|process)/, 'Code execution & processes'],
  [/^(image_|text_to_speech|vision_|video_)/, 'Media & vision'],
  [/^(json_parse|datetime_now|memory_recall)$/, 'Utilities & memory'],
];
const categorize = (n) =>
  (CATEGORY_RULES.find(([re]) => re.test(n)) ?? [null, 'Integrations (niche)'])[1];

// Split "summary. Args: {...}" so the argument hint renders as code (escaped, and
// safe from Vue template parsing in the docs site).
const esc = (s) => {
  const [summary, args] = s.split(/\s*Args:\s*/);
  const clean = (t) => t.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\{\{/g, '{ {');
  return args ? `${clean(summary)}<br>\`${clean(args)}\`` : clean(summary);
};

function renderTools(tools, defaults) {
  const groups = new Map();
  for (const t of tools) {
    const c = categorize(t.name);
    if (!groups.has(c)) groups.set(c, []);
    groups.get(c).push(t);
  }
  const onByDefault = tools.filter((t) => defaults.get(t.name) === true).length;
  const lines = [
    '<!-- GENERATED by scripts/docs-generate.mjs from packages/tools/src — do not edit by hand. -->',
    '',
    '# Built-in tool catalog',
    '',
    `Anvio ships **${tools.length} built-in tools** behind the tool gateway (\`packages/tools\`).`,
    `**${onByDefault}** are enabled in the default \`tools/gateway.yaml\` that \`anvio init\` writes; every other tool`,
    'is **disabled until you enable it** — a tool that is missing from `gateway.yaml` is treated as disabled.',
    '',
    'Models call a tool as `anvio_tools__<name>` (native `tool_use` where the provider supports it, otherwise an',
    '`anvio_tool` fenced block). The argument hints below are the exact strings the model sees.',
    '',
    '::: tip Enable a tool',
    '```yaml',
    '# workspace/tools/gateway.yaml',
    'spec:',
    '  tools:',
    '    run_shell:',
    '      enabled: true',
    '```',
    'Then check it with `anvio tools list` and `anvio tools test <name>`.',
    ':::',
    '',
    '::: warning Live status',
    'Being listed here means the tool is implemented. Tools that call third-party services (Home Assistant, X, Spotify,',
    'Feishu, Yuanbao, Tinker-Atropos, Honcho, video generation) need credentials or an MCP server and several fall back to',
    'a mock when one is not configured. Treat those as _not verified live_.',
    ':::',
    '',
  ];
  for (const [cat, list] of [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(
      `## ${cat}`,
      '',
      '| Tool | Default | Description · arguments |',
      '| --- | --- | --- |',
    );
    for (const t of list.sort((a, b) => a.name.localeCompare(b.name))) {
      const d = defaults.get(t.name) === true ? 'on' : 'off';
      lines.push(`| \`${t.name}\` | ${d} | ${esc(t.description)} |`);
    }
    lines.push('');
  }
  lines.push(
    '## Related',
    '',
    '- [44 — Tool gateway](../44-tool-gateway.md): allow-list, egress policy, approvals',
    '- [MCP reference](./mcp.md): tools from external MCP servers',
    '',
  );
  return lines.join('\n');
}

// ---------- metrics ----------
function countProviders() {
  const src = read('packages/models/src/provider-catalog.ts');
  const compat = src.slice(
    src.indexOf('OPENAI_COMPATIBLE_PROVIDER_SPECS'),
    src.indexOf('NATIVE_PROVIDER_IDS'),
  );
  const ids = [...compat.matchAll(/^\s{4}id: '([a-z0-9-]+)'/gm)].map((m) => m[1]);
  const native = [...src.matchAll(/NATIVE_PROVIDER_IDS = \[([^\]]+)\]/g)][0][1]
    .match(/'([a-z]+)'/g)
    .map((s) => s.slice(1, -1));
  const custom = /'custom',\s*\]\s*as const/.test(src) ? ['custom'] : [];
  return [...native, ...ids, ...custom];
}

function countChannels() {
  const src = read('packages/channels/src/create-channels.ts');
  // Every adapter is constructed as `new <Name>Channel(` (WhatsApp is assigned first, then registered).
  return [...new Set([...src.matchAll(/new ([A-Z][A-Za-z]+)Channel\(/g)].map((m) => m[1]))];
}

const listDir = (p, filter) =>
  existsSync(join(root, p)) ? readdirSync(join(root, p)).filter(filter) : [];

function countSpecs() {
  let unit = 0;
  const walk = (dir) => {
    for (const e of readdirSync(dir)) {
      if (e === 'node_modules' || e === 'dist' || e.startsWith('.')) continue;
      const p = join(dir, e);
      if (statSync(p).isDirectory()) walk(p);
      else if (e.endsWith('.spec.ts')) unit++;
    }
  };
  walk(join(root, 'packages'));
  walk(join(root, 'apps'));
  const integration = listDir('tests/integration', (f) =>
    f.endsWith('.integration.spec.ts'),
  ).length;
  return { unit, integration };
}

function renderMetrics(tools, defaults) {
  const providers = countProviders();
  const channels = countChannels();
  const packages = listDir('packages', (f) =>
    existsSync(join(root, 'packages', f, 'package.json')),
  );
  const apps = listDir('apps', (f) => existsSync(join(root, 'apps', f, 'package.json')));
  const adrs = listDir('docs/adr', (f) => /^\d{4}-.*\.md$/.test(f));
  const docs = listDir('docs', (f) => f.endsWith('.md'));
  const specs = countSpecs();
  // Package manifests are not bumped per release; CHANGELOG.md is the release record.
  const version = read('CHANGELOG.md').match(/^## \[(\d+\.\d+\.\d+)\]/m)?.[1] ?? 'n/a';
  const row = (k, v, src) => `| ${k} | **${v}** | ${src} |`;
  return [
    '<!-- GENERATED by scripts/docs-generate.mjs — do not edit by hand. -->',
    '',
    '# Project metrics',
    '',
    'Every number on this page is **counted from the repository source** by `scripts/docs-generate.mjs`',
    'and re-checked in CI (`docs` workflow). They describe what the code contains — not runtime usage,',
    'not executions, not adoption.',
    '',
    '## Platform surface',
    '',
    '| Metric | Value | Counted from |',
    '| --- | --- | --- |',
    row('Built-in tools', tools.length, '`packages/tools/src/tool-descriptions.ts`'),
    row(
      'Tools enabled by default',
      [...defaults.values()].filter(Boolean).length,
      '`DEFAULT_TOOL_GATEWAY_YAML` in `packages/tools/src/gateway.ts`',
    ),
    row('Model providers', providers.length, '`packages/models/src/provider-catalog.ts`'),
    row('Channel adapters', channels.length, '`packages/channels/src/create-channels.ts`'),
    '',
    `Providers: ${providers.map((p) => `\`${p}\``).join(', ')}.`,
    '',
    `Channels: ${channels.map((c) => `\`${c}\``).join(', ')}.`,
    '',
    '## Codebase',
    '',
    '| Metric | Value | Counted from |',
    '| --- | --- | --- |',
    row('Latest release', version, '`CHANGELOG.md`'),
    row('Workspace packages', packages.length, '`packages/*/package.json`'),
    row('Apps', apps.length, '`apps/*/package.json`'),
    row('Unit spec files', specs.unit, '`**/*.spec.ts` in `packages/` and `apps/`'),
    row('Integration spec files', specs.integration, '`tests/integration/*.integration.spec.ts`'),
    row('Architecture decision records', adrs.length, '`docs/adr/NNNN-*.md`'),
    row('Top-level docs pages', docs.length, '`docs/*.md`'),
    '',
    '## Not reported here',
    '',
    '- **Test coverage** — the repository has no coverage reporter configured, so no coverage figure is published.',
    '- **Stars, forks, contributors, releases** — live repository data; see the badges on the',
    '  [GitHub repository](https://github.com/viantonugroho11/Anvio) instead.',
    '',
  ].join('\n');
}

// ---------- write ----------
const tools = parseToolDescriptions();
if (tools.length < 10) throw new Error(`parsed only ${tools.length} tools — parser out of date`);
const defaults = parseGatewayDefaults();
const outputs = {
  'docs/reference/builtin-tools.md': renderTools(tools, defaults),
  'docs/reference/project-metrics.md': renderMetrics(tools, defaults),
};
let stale = false;
for (const [p, content] of Object.entries(outputs)) {
  const abs = join(root, p);
  const current = existsSync(abs) ? readFileSync(abs, 'utf-8') : '';
  if (current === content) continue;
  if (check) {
    console.error(`stale: ${p} (run: node scripts/docs-generate.mjs)`);
    stale = true;
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote ${p}`);
  }
}
if (stale) process.exit(1);
